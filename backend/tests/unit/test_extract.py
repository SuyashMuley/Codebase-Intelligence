import io
import tarfile
import time

import pytest

from app.core.errors import FetchTimeout, GithubUnavailable, RepoTooLarge
from app.services.github.extract import ExtractedFile, FetchLimits, FetchStats, extract_files
from tests.helpers import DEFAULT_FILES, DEFAULT_KEPT, PREFIX, make_tarball

LIMITS = FetchLimits(
    max_file_bytes=256 * 1024,
    max_files=100,
    max_total_bytes=5 * 1024 * 1024,
    max_uncompressed_bytes=50 * 1024 * 1024,
    max_members=1000,
)


def run(
    data: bytes, limits: FetchLimits = LIMITS, deadline_in: float = 30.0
) -> tuple[list[ExtractedFile], FetchStats]:
    stats = FetchStats()
    files = list(extract_files(io.BytesIO(data), limits, time.monotonic() + deadline_in, stats))
    return files, stats


def test_keeps_supported_source_and_records_informative_skips() -> None:
    files, stats = run(make_tarball(DEFAULT_FILES))
    kept = {f.path for f in files if f.skipped_reason is None}
    assert kept == DEFAULT_KEPT
    by_path = {f.path: f for f in files}
    assert by_path["src/app.py"].language == "python"
    assert by_path["src/app.py"].content == DEFAULT_FILES["src/app.py"]
    assert len(by_path["src/app.py"].sha256) == 64
    # Oversized supported-language file is recorded without content.
    assert by_path["src/big.py"].skipped_reason == "too_large"
    assert by_path["src/big.py"].content is None
    # Vendored, unsupported and secret files are counted but never yielded.
    assert "node_modules/lib/index.js" not in by_path
    assert ".env" not in by_path
    assert "README.md" not in by_path
    assert stats.files_kept == len(DEFAULT_KEPT)
    assert stats.skipped == {
        "unsupported": 2,
        "vendored": 1,
        "secret_file": 1,
        "too_large": 1,
    }


def test_secret_file_content_is_never_read_or_returned() -> None:
    files, _ = run(make_tarball({".env": "API_KEY=sk-live-123\n", "a.py": "x = 1\n"}))
    assert all("sk-live-123" not in (f.content or "") for f in files)
    assert [f.path for f in files] == ["a.py"]


def test_unsafe_paths_are_skipped() -> None:
    def extras(tf: tarfile.TarFile) -> None:
        for name in (PREFIX + "../evil.py", "/abs/evil.py", PREFIX + "a/../../evil.py"):
            info = tarfile.TarInfo(name)
            info.size = 5
            tf.addfile(info, io.BytesIO(b"x = 1"))

    files, stats = run(make_tarball({"ok.py": "x = 1\n"}, extras=extras))
    assert [f.path for f in files] == ["ok.py"]
    assert stats.skipped["unsafe_path"] == 3


def test_links_and_directories_are_ignored() -> None:
    def extras(tf: tarfile.TarFile) -> None:
        link = tarfile.TarInfo(PREFIX + "link.py")
        link.type = tarfile.SYMTYPE
        link.linkname = "/etc/passwd"
        tf.addfile(link)
        hard = tarfile.TarInfo(PREFIX + "hard.py")
        hard.type = tarfile.LNKTYPE
        hard.linkname = PREFIX + "ok.py"
        tf.addfile(hard)
        d = tarfile.TarInfo(PREFIX + "pkg")
        d.type = tarfile.DIRTYPE
        tf.addfile(d)

    files, _ = run(make_tarball({"ok.py": "x = 1\n"}, extras=extras))
    assert [f.path for f in files] == ["ok.py"]


@pytest.mark.parametrize(
    ("content", "reason"),
    [
        (b"x = 1\x00\n", "binary"),
        (b"\xff\xfe\xfa invalid utf8 \x80", "binary"),
        (b"// Code generated by protoc. DO NOT EDIT.\npackage x\n", "generated"),
    ],
)
def test_content_level_skips(content: bytes, reason: str) -> None:
    files, stats = run(make_tarball({"sub/f.go": content}))
    assert len(files) == 1
    assert files[0].skipped_reason == reason
    assert files[0].content is None
    assert stats.files_kept == 0
    assert stats.skipped == {reason: 1}


def test_too_many_source_files() -> None:
    limits = FetchLimits(**{**LIMITS.__dict__, "max_files": 3})
    data = make_tarball({f"f{i}.py": "x = 1\n" for i in range(4)})
    with pytest.raises(RepoTooLarge, match="more than 3"):
        run(data, limits)


def test_total_source_bytes_cap() -> None:
    limits = FetchLimits(**{**LIMITS.__dict__, "max_total_bytes": 100})
    data = make_tarball({"a.py": "x" * 60, "b.py": "y" * 60})
    with pytest.raises(RepoTooLarge, match="source exceeds"):
        run(data, limits)


def test_uncompressed_size_cap_uses_declared_sizes() -> None:
    # Highly compressible: tiny on the wire, large when expanded (a "zip bomb" shape).
    data = make_tarball({"junk.bin": b"\x00" * 2_000_000})
    assert len(data) < 10_000
    limits = FetchLimits(**{**LIMITS.__dict__, "max_uncompressed_bytes": 1_000_000})
    with pytest.raises(RepoTooLarge, match="uncompressed"):
        run(data, limits)


def test_member_count_cap() -> None:
    limits = FetchLimits(**{**LIMITS.__dict__, "max_members": 5})
    data = make_tarball({f"d/f{i}.txt": "x" for i in range(10)})
    with pytest.raises(RepoTooLarge, match="too many entries"):
        run(data, limits)


def test_deadline_raises_retryable_timeout() -> None:
    with pytest.raises(FetchTimeout) as exc:
        run(make_tarball({"a.py": "x = 1\n"}), deadline_in=-1.0)
    assert exc.value.retryable


@pytest.mark.parametrize("data", [b"definitely not gzip", b"", make_tarball({"a.py": "x"})[:40]])
def test_corrupt_archive_is_reported_as_unavailable(data: bytes) -> None:
    with pytest.raises(GithubUnavailable):
        run(data)
