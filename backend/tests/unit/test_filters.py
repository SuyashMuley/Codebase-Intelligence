import pytest

from app.services.github.filters import (
    classify_path,
    has_generated_header,
    looks_binary,
    normalize_member_path,
)


@pytest.mark.parametrize(
    ("name", "expected"),
    [
        ("owner-repo-abc/src/app.py", "src/app.py"),
        ("owner-repo-abc/README.md", "README.md"),
        ("owner-repo-abc/a/b/c.go", "a/b/c.go"),
        ("owner-repo-abc/../evil.py", None),
        ("owner-repo-abc/a/../../evil.py", None),
        ("/etc/passwd", None),
        ("owner-repo-abc//double.py", None),
        ("owner-repo-abc/./x.py", None),
        ("owner-repo-abc/a\\b.py", None),
        ("owner-repo-abc/ctl\x07.py", None),
        ("owner-repo-abc/nul\x00.py", None),
        ("toplevel-only", None),
        ("", None),
        ("x/" + "a" * 600, None),
    ],
)
def test_normalize_member_path(name: str, expected: str | None) -> None:
    assert normalize_member_path(name) == expected


@pytest.mark.parametrize(
    ("path", "language", "reason"),
    [
        ("src/app.py", "python", None),
        ("src/app.PY", "python", None),
        ("web/Button.tsx", "typescript", None),
        ("web/index.jsx", "javascript", None),
        ("lib/x.mjs", "javascript", None),
        ("cmd/main.go", "go", None),
        ("README.md", None, "unsupported"),
        ("assets/logo.png", None, "unsupported"),
        ("Makefile", None, "unsupported"),
        ("node_modules/pkg/index.js", "javascript", "vendored"),
        ("a/vendor/b/c.go", "go", "vendored"),
        ("dist/bundle.js", "javascript", "vendored"),
        (".venv/lib/site.py", "python", "vendored"),
        ("static/app.min.js", "javascript", "generated"),
        ("api/service.pb.go", "go", "generated"),
        ("proto/x_pb2.py", "python", "generated"),
        ("types/index.d.ts", "typescript", "generated"),
        ("config/credentials.json", None, "secret_file"),
        ("deploy/secrets.yaml", None, "secret_file"),
        ("deploy/secret.toml", None, "secret_file"),
        ("home/credentials", None, "secret_file"),
        # Source code that merely has "credentials" or "secrets" in its name is still source code.
        ("app/services/auth/credentials.py", "python", None),
        ("src/secrets.ts", "typescript", None),
        ("internal/credentials.go", "go", None),
        ("lib/secrets.js", "javascript", None),
        ("src/credentials_store.py", "python", None),
        (".env", None, "secret_file"),
        (".env.production", None, "secret_file"),
        ("deploy/id_rsa", None, "secret_file"),
        ("certs/server.pem", None, "secret_file"),
        ("config/credentials.json", None, "secret_file"),
        # a directory named like a vendored dir only counts as a directory, not a file name
        ("src/build.py", "python", None),
    ],
)
def test_classify_path(path: str, language: str | None, reason: str | None) -> None:
    assert classify_path(path) == (language, reason)


def test_binary_detection() -> None:
    assert looks_binary(b"abc\x00def")
    assert not looks_binary("héllo wörld".encode())
    # A NUL after the first 8000 bytes is not inspected.
    assert not looks_binary(b"a" * 9000 + b"\x00")


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("// Code generated by protoc. DO NOT EDIT.\npackage x\n", True),
        ("/* @generated */\nexport {}\n", True),
        ("// Code generated by hand? no\n", False),
        ("package main\n", False),
        ("x = 1\n" * 500 + "# @generated", False),  # marker beyond the header window
    ],
)
def test_generated_header(text: str, expected: bool) -> None:
    assert has_generated_header(text) is expected
